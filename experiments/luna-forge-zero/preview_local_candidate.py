"""Inspect and sample the LATEST trained local MiniCoder candidate.

Only reads weights under the Luna experiment external_data directory.
Never executes generated source, never promotes a candidate, never reads the
user's Grand Chase data, and never uploads local files.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent
DATA=HERE/"external_data"
PREFIX="local-candidate-"

def candidates(base: Path=DATA) -> list[Path]:
    base=Path(base)
    if not base.is_dir():
        return []
    return sorted(
        (p for p in base.iterdir() if p.is_dir() and p.name.startswith(PREFIX)
         and (p/"report.json").is_file() and (p/"weights.pt").is_file()),
        key=lambda p:p.name,
        reverse=True,
    )

def verify_candidate(candidate: Path, base: Path=DATA) -> tuple[dict,Path]:
    candidate=Path(candidate).resolve()
    base=Path(base).resolve()
    if candidate.parent!=base or not candidate.name.startswith(PREFIX):
        raise ValueError("Only local-candidate-* under Luna external_data may be opened")
    report_path=candidate/"report.json"
    weights=candidate/"weights.pt"
    if not report_path.is_file() or not weights.is_file():
        raise FileNotFoundError("Candidate is incomplete")
    report=json.loads(report_path.read_text(encoding="utf-8"))
    if report.get("status")!="experiment_not_promoted" or report.get("promotion_allowed") is not False:
        raise ValueError("Candidate provenance/promotion status unexpected")
    if report.get("grandchase_raw_repositories_in_training")!=0:
        raise ValueError("The source gate did not approve the candidate")
    cfg=report.get("config")
    if not isinstance(cfg,dict) or not {"vocab","block","width","heads","layers"}<=cfg.keys():
        raise ValueError("Candidate architecture missing")
    if weights.stat().st_size > 64 * 1024 * 1024:
        raise ValueError("Checkpoint exceeds the 64 MiB file-size guard")
    expected=report.get("weights_sha256")
    if not isinstance(expected,str) or len(expected)!=64:
        raise ValueError("Missing SHA-256 provenance")
    digest=hashlib.sha256()
    with weights.open("rb") as stream:
        for part in iter(lambda:stream.read(1024*1024),b""):
            digest.update(part)
    if digest.hexdigest()!=expected:
        raise ValueError("Candidate SHA-256 mismatch: checkpoint may be corrupt")
    return report,weights

def preview(candidate: Path, request: str, chars: int=160, seed: int=123, base: Path=DATA)->dict:
    report,weights=verify_candidate(candidate,base)
    if not 1<=chars<=320:
        raise ValueError("Generate only 1..320 characters")
    if not request.strip() or len(request)>1000:
        raise ValueError("A nonempty task of at most 1000 characters is required")
    import torch
    from luna_codegen_model import Config,LunaMiniCoder
    torch.set_num_threads(min(4,torch.get_num_threads()))
    model=LunaMiniCoder(Config(**report["config"]))
    model.load_state_dict(torch.load(weights,map_location="cpu",weights_only=True,mmap=True),assign=True)
    model.eval()
    torch.manual_seed(seed)
    prompt="TASK: "+request+"\nLANGUAGE: javascript\nCODE:\n"
    output=model.generate(prompt,chars=chars,temperature=.6)
    return {
        "checkpoint":candidate.name,
        "checkpoint_sha256":report["weights_sha256"],
        "source":"generated by local trained MiniCoder candidate, not a human template",
        "request":request,"generated_text":output[len(prompt):],
        "generated_code_executed":False,"syntax_verified":False,
        "model_promoted":False,
        "warning":"Experimental character model. Output may be invalid JavaScript. Do not execute unreviewed code.",
    }

def main():
    p=argparse.ArgumentParser(description="Preview newly trained local MiniCoder candidates")
    p.add_argument("action",choices=("list","generate"))
    p.add_argument("--task",default="Write an original 2D platformer jump function")
    p.add_argument("--chars",type=int,default=160)
    a=p.parse_args()
    available=candidates()
    if a.action=="list":
        print(json.dumps({"candidate_count":len(available),
                          "candidates":[x.name for x in available],
                          "active_model_unchanged":True},indent=2))
        return
    if not available:
        raise FileNotFoundError("No local-candidate-* checkpoints found. Train with menu option 4 first.")
    print(json.dumps(preview(available[0],a.task,chars=a.chars),ensure_ascii=False,indent=2))

if __name__=="__main__":
    main()
