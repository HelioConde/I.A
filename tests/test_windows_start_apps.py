"""Windows Start Menu catalog and guarded program activation (mocked, no real launch)."""
from __future__ import annotations

import json
import sys
import tempfile
import types
import unittest
from pathlib import Path
from unittest.mock import patch, MagicMock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from brain_ssd.chat import windows_apps


class TestStartApps(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.windows = Path(temp.name) / "Windows"
        self.system = self.windows / "System32"
        ps = self.system / "WindowsPowerShell" / "v1.0" / "powershell.exe"
        ps.parent.mkdir(parents=True)
        ps.write_bytes(b"stub")
        (self.windows / "explorer.exe").write_bytes(b"stub")
        self.os_patch = patch.object(windows_apps, "os", types.SimpleNamespace(name="nt"))
        self.os_patch.start()
        self.addCleanup(self.os_patch.stop)
        system_patch = patch.object(windows_apps, "_system_dir", return_value=self.system)
        system_patch.start()
        self.addCleanup(system_patch.stop)
        self.entries = [
            {"Name": "Calculadora", "AppID": "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"},
            {"Name": "Steam", "AppID": "Steam!App"},
            {"Name": "Visual Studio Code", "AppID": "Microsoft.AutoGenerated.{AABBCCDD}"},
            {"Name": "Windows PowerShell", "AppID": "Microsoft.Windows.PowerShell"},
            {"Name": "Steam Beta", "AppID": "Steam.Beta"},
        ]

    def _catalog(self, items=None):
        payload = json.dumps(self.entries if items is None else items).encode("utf-8")
        return patch.object(windows_apps.subprocess, "run",
                            return_value=types.SimpleNamespace(returncode=0, stdout=payload))

    def test_catalog_only_calls_fixed_get_startapps_and_no_user_shell(self):
        with self._catalog() as run:
            result = windows_apps.start_menu_apps("Steam")
        self.assertEqual(result["total_matches"], 2)
        self.assertEqual(len(result["items"]), 2)
        cmd = run.call_args.args[0]
        self.assertTrue(cmd[0].endswith("powershell.exe"))
        self.assertIn("Get-StartApps", cmd[-1])
        self.assertNotIn("Steam", cmd[-1], "User-supplied filter must not reach PowerShell")
        self.assertFalse(run.call_args.kwargs["check"] or False)
        self.assertNotIn("shell", run.call_args.kwargs)

    def test_exact_match_runs_one_registered_app_through_explorer(self):
        with self._catalog(), patch.object(windows_apps.subprocess, "Popen",
                                            return_value=types.SimpleNamespace(pid=4321)) as popen:
            report = windows_apps.run_start_app("Steam")
        self.assertEqual(report["label"], "Steam")
        self.assertEqual(report["status"], "requested")
        self.assertEqual(report["started_pid"], 4321)
        command = popen.call_args.args[0]
        self.assertTrue(command[0].endswith("explorer.exe"))
        self.assertEqual(command[1], "shell:AppsFolder\\Steam!App")
        self.assertIs(popen.call_args.kwargs["shell"], False)

    def test_ambiguous_partial_and_command_injection_rejected(self):
        with self._catalog(), patch.object(windows_apps.subprocess, "Popen") as popen:
            with self.assertRaisesRegex(ValueError, "ambíguo"):
                windows_apps.run_start_app("stea")
            for name in ("cmd", "Windows PowerShell", "Steam & calc.exe",
                         "C:\\Windows\\system32\\calc.exe", "Steam; whoami"):
                with self.subTest(name=name):
                    with self.assertRaises(ValueError):
                        windows_apps.run_start_app(name)
            popen.assert_not_called()

    def test_invalid_registered_ids_are_not_launchable(self):
        with self._catalog([{"Name": "Bad", "AppID": "start;calc.exe"},
                            {"Name": "Empty", "AppID": ""},
                            {"Name": "Good", "AppID": "Good!App"}]):
            result = windows_apps.start_menu_apps()
        self.assertEqual([item["name"] for item in result["items"]], ["Good"])


if __name__ == "__main__":
    unittest.main()
